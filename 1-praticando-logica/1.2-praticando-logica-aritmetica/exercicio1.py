# 1. Quatro operações

# - **Entrada:** defina `a = 12` e `b = 4`.
# - **Processamento:** calcule soma, subtração, multiplicação e divisão.
# - **Saída:** mostre cada resultado com um rótulo.

# Resultados esperados: `16`, `8`, `48` e `3.0`.
a = 12
b = 4
resultado = a + b
print(f"o resultado da soma entre {a} e {b} é: {resultado}")

resultado = a - b
print(resultado)

resultado = a * b
print(resultado)

resultado = a / b
print(resultado)
