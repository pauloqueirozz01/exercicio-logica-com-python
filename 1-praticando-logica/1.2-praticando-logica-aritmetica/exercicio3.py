# 3. Divisão, quociente e resto

# - **Entrada:** use `17` como dividendo e `5` como divisor.
# - **Processamento:** calcule os resultados de `/`, `//` e `%` em variáveis diferentes.
# - **Saída:** mostre `3.4`, `3` e `2`, identificando cada operação.

a = 17
b = 5

primeira_operacao= a / b
print(f"Resultado da divisão de {a} e {b} = {primeira_operacao}")

segunda_operacao = a // b
print(f"Quociente da divisão de {a} e {b} = {segunda_operacao}")

terceira_operacao = a % b
print(f"Resto da divisão entre {a} e {b} = {terceira_operacao}")